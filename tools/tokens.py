"""Design token generator (README 8.2).

Reads shared/design/tokens.json and writes one file per consumer:

- app/theme/tokens.generated.ts                      (Expo app + web)
- backend/app/admin/static/tokens.generated.css      (admin UI)
- app/modules/famapp-engine/engine-android/src/main/res/values(-night)/colors_generated.xml

Only semantic tokens are exported; base tokens are the palette they point at.

    python tools/tokens.py           write the generated files
    python tools/tokens.py --check   fail if a generated file is missing or stale
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path("shared/design/tokens.json")
TS_OUT = Path("app/theme/tokens.generated.ts")
CSS_OUT = Path("backend/app/admin/static/tokens.generated.css")
ANDROID_RES = Path("app/modules/famapp-engine/engine-android/src/main/res")
XML_LIGHT_OUT = ANDROID_RES / "values/colors_generated.xml"
XML_DARK_OUT = ANDROID_RES / "values-night/colors_generated.xml"

HEADER = "Generated by tools/tokens.py from shared/design/tokens.json. Do not edit; run `make tokens`."
SEGMENT = re.compile(r"^[a-zA-Z0-9]+$")
HEX = re.compile(r"^#[0-9a-f]{6}$")
REF = re.compile(r"^\{([a-zA-Z0-9.]+)\}$")
GROUPS = ("color", "space", "radius", "fontSize", "fontWeight", "duration")
CSS_UNITS = {"space": "px", "radius": "px", "fontSize": "px", "fontWeight": "", "duration": "ms"}


class TokenError(Exception):
    pass


def _flatten(tree: dict, prefix: tuple[str, ...] = ()) -> dict[tuple[str, ...], object]:
    out: dict[tuple[str, ...], object] = {}
    for key, value in tree.items():
        if not SEGMENT.match(key):
            raise TokenError(f"invalid token name segment {key!r} in {'.'.join(prefix) or 'root'}")
        path = (*prefix, key)
        is_leaf = not isinstance(value, dict) or set(value) == {"light", "dark"}
        if is_leaf:
            out[path] = value
        else:
            out.update(_flatten(value, path))
    return out


def _resolve(ref: object, base: dict[tuple[str, ...], object], where: str) -> object:
    match = REF.match(ref) if isinstance(ref, str) else None
    if not match:
        raise TokenError(f"{where}: semantic tokens must reference a base token like '{{color.gray.50}}', got {ref!r}")
    path = tuple(match.group(1).split("."))
    if path not in base:
        raise TokenError(f"{where}: unknown base token {match.group(1)!r}")
    return base[path]


def load(source: Path) -> dict[str, dict[tuple[str, ...], object]]:
    """Return semantic tokens per group, resolved to values. Colors resolve to {"light", "dark"}."""
    try:
        data = json.loads(source.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise TokenError(f"{source}: invalid JSON: {exc}") from exc
    if set(data) != {"base", "semantic"}:
        raise TokenError(f"{source}: top level must be exactly 'base' and 'semantic'")
    base = _flatten(data["base"])
    for path, value in base.items():
        name = ".".join(path)
        if path[0] not in GROUPS:
            raise TokenError(f"base token {name}: unknown group {path[0]!r}")
        if path[0] == "color":
            if not (isinstance(value, str) and HEX.match(value)):
                raise TokenError(f"base token {name}: colors must be lowercase #rrggbb, got {value!r}")
        elif not isinstance(value, int) or isinstance(value, bool):
            raise TokenError(f"base token {name}: must be an integer, got {value!r}")

    semantic = _flatten(data["semantic"])
    result: dict[str, dict[tuple[str, ...], object]] = {group: {} for group in GROUPS}
    for path, value in semantic.items():
        name = ".".join(path)
        group = path[0]
        if group not in GROUPS:
            raise TokenError(f"semantic token {name}: unknown group {group!r}")
        if group == "color":
            if not (isinstance(value, dict) and set(value) == {"light", "dark"}):
                raise TokenError(f"semantic token {name}: colors need exactly a 'light' and a 'dark' value")
            resolved = {mode: _resolve(value[mode], base, f"{name}.{mode}") for mode in ("light", "dark")}
            for mode, ref in value.items():
                if not str(ref).startswith("{color."):
                    raise TokenError(f"semantic token {name}.{mode}: must reference a color token")
        else:
            if not str(value).startswith("{" + group + "."):
                raise TokenError(f"semantic token {name}: must reference a {group} token")
            resolved = _resolve(value, base, name)
        result[group][path[1:]] = resolved
    if not result["color"]:
        raise TokenError("no semantic color tokens")
    return result


def _kebab(segment: str) -> str:
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"-\1", segment).lower()


def _snake(segment: str) -> str:
    return _kebab(segment).replace("-", "_")


def _ts_key(segment: str) -> str:
    return segment if re.match(r"^[a-zA-Z_][a-zA-Z0-9_]*$", segment) else json.dumps(segment)


def _nest(flat: dict[tuple[str, ...], object]) -> dict:
    tree: dict = {}
    for path, value in flat.items():
        node = tree
        for segment in path[:-1]:
            node = node.setdefault(segment, {})
        node[path[-1]] = value
    return tree


def _ts_object(tree: dict, indent: int) -> str:
    pad = "  " * indent
    lines = ["{"]
    for key, value in tree.items():
        rendered = _ts_object(value, indent + 1) if isinstance(value, dict) else json.dumps(value)
        lines.append(f"{pad}  {_ts_key(key)}: {rendered},")
    lines.append(f"{pad}}}")
    return "\n".join(lines)


def render_ts(tokens: dict) -> str:
    out = [f"// {HEADER}", ""]
    colors = tokens["color"]
    for mode, annotation in (("light", ""), ("dark", ": ColorTokens")):
        tree = _nest({path: value[mode] for path, value in colors.items()})
        out.append(f"export const {mode}Colors{annotation} = {_ts_object(tree, 0)};")
        out.append("")
        if mode == "light":
            out.append("export type ColorTokens = typeof lightColors;")
            out.append("")
    for group in GROUPS[1:]:
        out.append(f"export const {group} = {_ts_object(_nest(tokens[group]), 0)} as const;")
        out.append("")
    return "\n".join(out)


def _css_var(group: str, path: tuple[str, ...]) -> str:
    return "--" + "-".join(_kebab(s) for s in (group, *path))


def render_css(tokens: dict) -> str:
    def color_block(mode: str, indent: str) -> list[str]:
        return [f"{indent}{_css_var('color', p)}: {v[mode]};" for p, v in tokens["color"].items()]

    out = [f"/* {HEADER} */", "", ":root {"]
    out += color_block("light", "  ")
    for group in GROUPS[1:]:
        unit = CSS_UNITS[group]
        out += [f"  {_css_var(group, p)}: {v}{unit};" for p, v in tokens[group].items()]
    out += ["}", "", "@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {']
    out += color_block("dark", "    ")
    out += ["  }", "}", "", ':root[data-theme="dark"] {']
    out += color_block("dark", "  ")
    out += ["}", ""]
    return "\n".join(out)


def render_xml(tokens: dict, mode: str) -> str:
    out = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER} -->", "<resources>"]
    for path, value in tokens["color"].items():
        name = "_".join(_snake(s) for s in ("color", *path))
        out.append(f'    <color name="{name}">{value[mode]}</color>')
    out += ["</resources>", ""]
    return "\n".join(out)


def outputs(root: Path) -> dict[Path, str]:
    tokens = load(root / SOURCE)
    return {
        TS_OUT: render_ts(tokens),
        CSS_OUT: render_css(tokens),
        XML_LIGHT_OUT: render_xml(tokens, "light"),
        XML_DARK_OUT: render_xml(tokens, "dark"),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail on missing or stale generated files")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        files = outputs(args.root)
    except TokenError as exc:
        print(f"tokens: {exc}", file=sys.stderr)
        return 1
    stale = []
    for rel, content in files.items():
        target = args.root / rel
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(rel)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
            print(f"tokens: wrote {rel}")
    if stale:
        for rel in stale:
            print(f"tokens: {rel} is missing or stale", file=sys.stderr)
        print("tokens: run `make tokens` and commit the result", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
